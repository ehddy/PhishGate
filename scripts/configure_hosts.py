#!/usr/bin/env python3
"""Print, apply, or remove every local hostname used by PhishGate.

The single managed block contains the optional G1 seed-derived gateway domain
and the original source hostnames used by G2/G3 Host-header routing. Applying
or removing it is explicit because the real hosts file normally requires
administrator privileges.

    python3 scripts/configure_hosts.py
    sudo python3 scripts/configure_hosts.py --apply
    sudo python3 scripts/configure_hosts.py --remove
"""

from __future__ import annotations

import argparse
import csv
import os
import re
import sys
from pathlib import Path
from urllib.parse import urlparse


ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from app.runtime_config import derive_local_domain


ENV_PATH = ROOT / ".env"
BENIGN_CSV = ROOT / "data" / "manual_benign_annotation.csv"
PHISHING_CSV = ROOT / "data" / "manual_annotation.csv"
DEFAULT_HOSTS_PATH = Path("/etc/hosts")
BEGIN_MARKER = "# BEGIN PhishGate hosts (managed by scripts/configure_hosts.py)"
END_MARKER = "# END PhishGate hosts"
LEGACY_BLOCKS = (
    (
        "# BEGIN PhishGate local domain (auto-generated by scripts/network/local_domain_hosts.py --apply -- do not edit by hand, use scripts/network/local_domain_hosts.py --remove to undo)",
        "# END PhishGate local domain",
    ),
    (
        "# BEGIN PhishGate manual dataset (auto-generated by scripts/network/manual_hosts.py --apply -- do not edit by hand, use scripts/network/manual_hosts.py --remove to undo)",
        "# END PhishGate manual dataset",
    ),
)


def read_env() -> dict[str, str]:
    if not ENV_PATH.exists():
        raise SystemExit(f"{ENV_PATH} not found. Copy .env.example to .env first.")
    values: dict[str, str] = {}
    for raw_line in ENV_PATH.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$", line)
        if match:
            values[match.group(1)] = match.group(2).strip()
    return values


def gateway_domain(env: dict[str, str]) -> str | None:
    seed = env.get("PHISHGATE_SEED", "").strip()
    style = env.get("PHISHGATE_DOMAIN_STYLE", "off").strip() or "off"
    if not seed:
        raise SystemExit("PHISHGATE_SEED is empty in .env.")
    try:
        return derive_local_domain(seed, style)
    except ValueError as error:
        raise SystemExit(str(error)) from error


def hostnames_from_csv(path: Path) -> list[str]:
    if not path.exists():
        return []
    seen: dict[str, None] = {}
    with path.open(encoding="utf-8", newline="") as annotation_file:
        for row in csv.DictReader(annotation_file):
            hostname = urlparse((row.get("source_url") or "").strip()).hostname
            if hostname:
                seen[hostname.lower()] = None
    return list(seen)


def mapping_groups() -> tuple[tuple[str, list[str]], ...]:
    domain = gateway_domain(read_env())
    return (
        ("G1 gateway", [domain] if domain else []),
        ("G2 phishing", hostnames_from_csv(PHISHING_CSV)),
        ("G3 benign", hostnames_from_csv(BENIGN_CSV)),
    )


def strip_block(lines: list[str], begin: str, end: str) -> list[str]:
    while begin in lines:
        start = lines.index(begin)
        try:
            finish = lines.index(end, start)
        except ValueError:
            return lines[:start]
        lines = lines[:start] + lines[finish + 1 :]
    return lines


def strip_managed_blocks(lines: list[str]) -> list[str]:
    lines = strip_block(lines, BEGIN_MARKER, END_MARKER)
    for begin, end in LEGACY_BLOCKS:
        lines = strip_block(lines, begin, end)
    while lines and not lines[-1]:
        lines.pop()
    return lines


def rendered_block(groups: tuple[tuple[str, list[str]], ...]) -> list[str]:
    block = [BEGIN_MARKER]
    for label, hostnames in groups:
        if not hostnames:
            continue
        block.append(f"# {label}")
        block.extend(f"127.0.0.1 {hostname}" for hostname in hostnames)
    block.append(END_MARKER)
    return block


def print_mappings(groups: tuple[tuple[str, list[str]], ...]) -> None:
    for label, hostnames in groups:
        print(f"=== {label} ({len(hostnames)}) ===")
        if hostnames:
            for hostname in hostnames:
                print(f"127.0.0.1 {hostname}")
        else:
            print("(none)")
        print()
    print("Apply all mappings: sudo python3 scripts/configure_hosts.py --apply")
    print("Remove them later: sudo python3 scripts/configure_hosts.py --remove")


def require_writable(path: Path, mode: str) -> None:
    if not path.exists():
        raise SystemExit(f"{path} does not exist.")
    if not os.access(path, os.W_OK):
        suffix = f" --hosts-file {path}" if path != DEFAULT_HOSTS_PATH else ""
        raise SystemExit(
            f"No write access to {path} -- rerun as:\n"
            f"    sudo python3 scripts/configure_hosts.py {mode}{suffix}"
        )


def apply_mappings(groups: tuple[tuple[str, list[str]], ...], path: Path) -> None:
    require_writable(path, "--apply")
    original = path.read_text(encoding="utf-8")
    lines = strip_managed_blocks(original.splitlines())
    block = rendered_block(groups)
    if len(block) == 2:
        raise SystemExit("No PhishGate hostnames are currently registered.")

    backup = path.with_name(path.name + ".before-phishgate")
    if not backup.exists():
        backup.write_text(original, encoding="utf-8")
        print(f"Backed up original {path} to {backup}")
    path.write_text("\n".join([*lines, "", *block, ""]), encoding="utf-8")
    total = sum(len(hostnames) for _, hostnames in groups)
    print(f"Wrote {total} PhishGate hostname(s) to {path}.")


def remove_mappings(path: Path) -> None:
    require_writable(path, "--remove")
    original = path.read_text(encoding="utf-8")
    lines = strip_managed_blocks(original.splitlines())
    updated = "\n".join([*lines, ""])
    if updated == original:
        print(f"No PhishGate hosts block found in {path}.")
        return
    path.write_text(updated, encoding="utf-8")
    print(f"Removed PhishGate hostname mappings from {path}.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--apply", action="store_true", help="Write the unified block.")
    mode.add_argument("--remove", action="store_true", help="Remove unified and legacy blocks.")
    parser.add_argument("--hosts-file", type=Path, default=DEFAULT_HOSTS_PATH)
    args = parser.parse_args()

    if args.remove:
        remove_mappings(args.hosts_file)
    elif args.apply:
        apply_mappings(mapping_groups(), args.hosts_file)
    else:
        print_mappings(mapping_groups())


if __name__ == "__main__":
    main()
