// DEV / PREVIEW ONLY. This module builds a GateConfig straight from URL query
// params so the screenshot harness can render any template x variant combo
// without a backend or an opaque gate token. It is imported ONLY through a
// dynamically-imported branch guarded by `import.meta.env.DEV`, which `vite
// build` replaces with the literal `false`; Rollup then dead-code-eliminates
// the branch and drops this whole module from every production bundle. A CI
// grep for the sentinel above fails the build if it ever leaks into dist/.
// It must never be referenced from a statically-live code path.
import { templateRegistry } from "../registry";
// Generated by the production rotation generator with
// challenge_rng("preview", "kit-8", "rotation-v3", 0).
import rotationPreviewImageUrl from "./assets/rotate-upright.png";
import type {
  ContextMode,
  CopyVariant,
  GateChallenge,
  GateConfig,
  GateDisplayContext,
  LayoutVariant,
  ThemeVariant,
} from "../types";

type ChallengeVariant = "blue" | "violet" | "mint";

const CHALLENGE_ACCENT: Record<ChallengeVariant, string> = {
  blue: "#174ea6",
  violet: "#6842a5",
  mint: "#176f60",
};

// theme_variant has four values; the server challenge palette has three.
// slate (no challenge counterpart) folds to blue so the theme sweep still
// visibly changes the challenge color.
function toChallengeVariant(theme: ThemeVariant): ChallengeVariant {
  if (theme === "violet") return "violet";
  if (theme === "mint") return "mint";
  return "blue";
}

function svgDataUrl(svg: string): string {
  // URI-encoded UTF-8 rather than base64 so any character (incl. emoji glyphs)
  // is representable; btoa() throws on non-Latin1 input.
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

function digitSvg(digits: string, variant: ChallengeVariant): string {
  const accent = CHALLENGE_ACCENT[variant];
  return svgDataUrl(
    `<svg xmlns="http://www.w3.org/2000/svg" width="320" height="100">` +
      `<rect width="320" height="100" fill="#edf4ff"/>` +
      `<text x="160" y="66" font-size="48" font-family="monospace" letter-spacing="14" ` +
      `text-anchor="middle" fill="${accent}">${digits}</text></svg>`,
  );
}

function textSvg(text: string, variant: ChallengeVariant): string {
  const accent = CHALLENGE_ACCENT[variant];
  return svgDataUrl(
    `<svg xmlns="http://www.w3.org/2000/svg" width="360" height="110">` +
      `<rect width="360" height="110" fill="#edf4ff"/>` +
      `<text x="180" y="72" font-size="44" font-family="monospace" letter-spacing="10" ` +
      `text-anchor="middle" fill="${accent}">${text}</text></svg>`,
  );
}

function cellSvg(index: number, variant: ChallengeVariant): string {
  const accent = CHALLENGE_ACCENT[variant];
  return svgDataUrl(
    `<svg xmlns="http://www.w3.org/2000/svg" width="120" height="120">` +
      `<rect width="120" height="120" fill="${accent}22"/>` +
      `<text x="60" y="74" font-size="40" text-anchor="middle" fill="${accent}">${index + 1}</text></svg>`,
  );
}

function areaSceneSvg(variant: ChallengeVariant): string {
  const accent = CHALLENGE_ACCENT[variant];
  // A 3x2 scene of simple glyphs; a car sits in one region (the mock target).
  const glyphs = ["★", "☂", "✚", "🚗", "☁", "✎"];
  let cells = `<rect width="360" height="240" fill="${accent}14"/>`;
  glyphs.forEach((glyph, index) => {
    const x = (index % 3) * 120 + 60;
    const y = Math.floor(index / 3) * 120 + 78;
    cells += `<text x="${x}" y="${y}" font-size="46" text-anchor="middle" fill="${accent}">${glyph}</text>`;
  });
  return svgDataUrl(`<svg xmlns="http://www.w3.org/2000/svg" width="360" height="240">${cells}</svg>`);
}

function mockChallenge(templateId: string, variant: ChallengeVariant): GateChallenge | undefined {
  switch (templateId) {
    case "custom-digit":
      return { kind: "digit-image", variant, image_data_url: digitSvg("48213", variant) };
    case "text-captcha":
      return { kind: "text-image", variant, image_data_url: textSvg("K7MQ9P", variant) };
    case "math-challenge":
      return { kind: "math-problem", variant, operator: "addition", prompt: "7 + 5 = ?" };
    case "image-grid":
      return {
        kind: "image-grid",
        variant,
        category_label: "traffic lights",
        cells: Array.from({ length: 9 }, (_, index) => cellSvg(index, variant)),
      };
    case "area-select":
      return {
        kind: "area-select",
        variant,
        category_label: "car",
        columns: 3,
        rows: 2,
        image_data_url: areaSceneSvg(variant),
      };
    case "rotate-upright":
      return {
        kind: "rotation",
        variant,
        step_count: 8,
        image_data_url: rotationPreviewImageUrl,
      };
    default:
      return undefined;
  }
}

function param<T extends string>(search: URLSearchParams, key: string, fallback: T): T {
  return (search.get(key) as T | null) ?? fallback;
}

function normalizeBrand(contextMode: ContextMode, brand: string | null): string | null {
  const safeBrand = brand && brand.trim() ? brand.trim() : null;
  return contextMode === "neutral" ? null : safeBrand;
}

export function buildPreviewConfig(search: string): GateConfig | null {
  const query = new URLSearchParams(search);
  const templateId = query.get("template_id");
  const definition = templateId ? templateRegistry[templateId] : undefined;
  if (!templateId || !definition) {
    return null;
  }

  const themeVariant = param<ThemeVariant>(query, "theme_variant", "blue");
  const contextMode = param<ContextMode>(query, "context_mode", "brand-label");
  const displayContext: GateDisplayContext = {
    brand: normalizeBrand(contextMode, query.get("brand") ?? "Example Service"),
    context_mode: contextMode,
    layout_variant: param<LayoutVariant>(query, "layout_variant", "centered"),
    copy_variant: param<CopyVariant>(query, "copy_variant", "standard"),
    theme_variant: themeVariant,
    variant_id: query.get("variant_id") ?? `preview-${templateId}`,
  };

  return {
    gate_type: definition.gateType,
    template_id: templateId,
    parameters: {},
    display_context: displayContext,
    challenge: mockChallenge(templateId, toChallengeVariant(themeVariant)),
  };
}
